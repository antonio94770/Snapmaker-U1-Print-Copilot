def test_thinner_layers_do_not_override_detected_configuration_risks(gcode, tmp_path):
    from copy import deepcopy

    from print_copilot.quality_audit import Finding

    baseline = report_for(gcode, tmp_path).variants[0]
    finer = deepcopy(baseline)
    finer.label = "finer"
    for parameter in finer.audit.parameters:
        if parameter.key == "layer_height":
            parameter.value = "0.1"
    assert min([baseline, finer], key=quality._recommendation_key) is finer
    finer.audit.findings.append(
        Finding(
            "texture",
            "warning",
            "Fuzzy skin enabled",
            "A textured surface conflicts with this smooth-finish candidate.",
            [],
            "Review the choice.",
            True,
        )
    )
    assert min([baseline, finer], key=quality._recommendation_key) is baseline


def test_written_observations_and_all_open_findings_required(gcode, tmp_path):
    report = report_for(gcode, tmp_path)
    with pytest.raises(quality.QualityError, match="Written visual"):
        quality.record_quality_review(
            report.report_path,
            variant="baseline",
            decision="accept_with_limitations",
            observations=" ",
        )
    with pytest.raises(quality.QualityError, match="Acknowledge"):
        quality.record_quality_review(
            report.report_path,
            variant="baseline",
            decision="accept_with_limitations",
            observations="Inspected both layers and the wall starts.",
        )
    receipt = quality.record_quality_review(
        report.report_path,
        variant="baseline",
        decision="accept_with_limitations",
        observations="Inspected both layers and the wall starts.",
        accepted_findings=required_codes(report),
    )
    assert receipt.status == "reviewed_with_limitations"
    assert not receipt.print_authorization and receipt.hardware_quality == "unverified"
    saved = json.loads(report.report_path.read_text())
    assert saved["review"]["observations"].startswith("Inspected")


@pytest.mark.parametrize("changed", ["source", "png", "viewer", "findings"])
def test_changed_evidence_invalidates_review(gcode, tmp_path, changed):
    report = report_for(gcode, tmp_path)
    if changed == "source":
        gcode.write_text(gcode.read_text() + "; changed\n")
    elif changed == "png":
        report.variants[0].preview.png_path.write_bytes(b"modified image")
    elif changed == "viewer":
        report.variants[0].preview.html_path.write_text("changed")
    else:
        data = json.loads(report.report_path.read_text())
        data["variants"][0]["audit"]["findings"] = []
        report.report_path.write_text(json.dumps(data))
    with pytest.raises(quality.QualityError, match="changed"):
        quality.record_quality_review(
            report.report_path,
            variant="baseline",
            decision="accept_with_limitations",
            observations="Checked.",
            accepted_findings=required_codes(report),
        )


def test_detected_errors_cannot_be_waived(gcode, tmp_path):
    gcode.write_text(gcode.read_text().replace("; layer_height = 0.2", "; layer_height = 0.9"))
    report = report_for(gcode, tmp_path)
    assert report.status == "blocked" and report.recommendation is None
    with pytest.raises(quality.QualityError, match="cannot be waived"):
        quality.record_quality_review(
            report.report_path,
            variant="baseline",
            decision="accept_with_limitations",
            observations="Looked at both layers.",
            accepted_findings=required_codes(report),
        )


