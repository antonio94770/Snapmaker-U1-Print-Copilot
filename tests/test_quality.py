def report_for(gcode, tmp_path):
    return quality.review_print(gcode, work_dir=tmp_path / "reviews")


def required_codes(report):
    return [
        f.code for f in report.variants[0].audit.findings if f.severity in {"warning", "unverified"}
    ]


def test_effective_inventory_and_pending_visual_review(gcode, tmp_path):
    report = report_for(gcode, tmp_path)
    assert report.status == "visual_review_pending"
    variant = report.variants[0]
    assert variant.time_s == 62 and variant.filament_g == 1
    assert variant.audit.tools_used == [0]
    assert variant.audit.peak_commanded_flow_mm3_s[0] == pytest.approx(2.40528)
    inventory = {p.key: p for p in variant.audit.parameters}
    assert inventory["layer_height"].coverage == "rule_checked"
    assert inventory["printable_area"].coverage == "rule_checked"
    assert inventory["unrecognised_future_key"].coverage == "listed_only"
    assert "<script>alert(1)</script>" not in report.html_path.read_text(encoding="utf-8")
    assert "&lt;script&gt;" in report.html_path.read_text(encoding="utf-8")
    assert variant.preview.layers_shown == [1, 2]
    assert variant.preview.png_path.read_bytes().startswith(b"\x89PNG")
    from test_render import decode_png

    pixels = decode_png(variant.preview.png_path.read_bytes())
    # Regression: passing byte colours to the float-image encoder produced
    # white paths and invisible white labels instead of the intended palette.
    assert ((pixels == [37, 99, 235]).all(axis=2)).sum() > 10
    assert ((pixels == [25, 35, 50]).all(axis=2)).sum() > 10


