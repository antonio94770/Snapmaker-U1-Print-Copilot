def test_cli_and_mcp_work_without_orca_and_expose_images(gcode, tmp_path, monkeypatch, capsys):
    monkeypatch.setenv("PRINT_COPILOT_WORK_DIR", str(tmp_path / "work"))
    monkeypatch.setenv("PRINT_COPILOT_ORCA_EXE", str(tmp_path / "absent.exe"))
    assert cli.main(["quality", str(gcode), "--json"]) == 0
    assert json.loads(capsys.readouterr().out)["status"] == "visual_review_pending"
    response = mcp_server.review_print(str(gcode))
